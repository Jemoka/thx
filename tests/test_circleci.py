"""Exercise the actual CI reporting shell without posting a Gerrit review."""

import json
import os
from pathlib import Path
import subprocess

import pytest
import yaml


@pytest.mark.parametrize("check_exit,report_exit", [(0, 0), (7, 0), (0, 22)])
def test_pre_commit_report_preserves_output_and_exit_status(tmp_path, check_exit, report_exit):
    config = yaml.safe_load(
        (Path(__file__).resolve().parents[1] / ".circleci/gerrit.yml").read_text()
    )
    command = next(
        step["run"]["command"]
        for step in config["jobs"]["gerrit-ci"]["steps"]
        if step.get("run", {}).get("name") == "Run pre-commit"
    ).replace("/tmp/", f"{tmp_path}/")
    # Exceed typical shell argument limits and include JSON and shell metacharacters.
    output = 'failure: "quoted" \\path ${literal} `literal` 雪\n' * 5000
    stderr = "stderr: final diagnostic\n"
    (tmp_path / "stdout").write_text(output)
    (tmp_path / "stderr").write_text(stderr)
    executables = tmp_path / "bin"
    executables.mkdir()
    uv = executables / "uv"
    uv.write_text(
        '#!/bin/bash\ncat "$TEST_DIR/stdout"\ncat "$TEST_DIR/stderr" >&2\nexit "$TEST_CHECK_EXIT"\n'
    )
    curl = executables / "curl"
    curl.write_text(
        '#!/bin/bash\nprintf "%s\\n" "$@" > "$TEST_DIR/curl-args"\nexit "$TEST_REPORT_EXIT"\n'
    )
    uv.chmod(0o755)
    curl.chmod(0o755)
    result = subprocess.run(
        ["bash", "-eo", "pipefail", "-c", command],
        env={
            **os.environ,
            "PATH": f"{executables}:{os.environ['PATH']}",
            "TEST_DIR": str(tmp_path),
            "TEST_CHECK_EXIT": str(check_exit),
            "TEST_REPORT_EXIT": str(report_exit),
            "GERRIT_USER": "test-user",
            "GERRIT_HTTP_PASSWORD": "test-password",
            "GERRIT_CHANGE": "123",
            "GERRIT_REVISION": "test-revision",
        },
        capture_output=True,
        text=True,
        timeout=10,
    )
    assert result.returncode == (report_exit or check_exit)
    assert result.stdout == output + stderr
    payload = json.loads((tmp_path / "gerrit-review.json").read_text())
    assert payload == {
        "tag": "autogenerated:circleci",
        "message": "CircleCI failed.\n\n" + output + stderr if check_exit else "CircleCI passed.",
        "labels": {"Verified": -1 if check_exit else 1},
    }
    args = (tmp_path / "curl-args").read_text().splitlines()
    assert args[args.index("--data-binary") + 1] == f"@{tmp_path}/gerrit-review.json"
    assert args[-1].endswith("/changes/123/revisions/test-revision/review")
    assert "test-password" not in payload["message"]
